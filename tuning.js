function getKoreanParticle(name) {
  if (!name) return "아";
  const lastChar = name.charAt(name.length - 1);
  const code = lastChar.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) {
    return (code - 0xac00) % 28 !== 0 ? "아" : "야";
  }
  return "야"; 
}

